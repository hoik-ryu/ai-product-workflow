# ---------------------------------------------------------------- 입력: 기획 게이트·디자인 상태
def design_status(project: Path) -> dict:
    """product_design.py status(읽기 전용)를 호출합니다. design.json이 없으면 absent."""
    if not (project / DESIGN_STATE_REL).exists():
        return {"absent": True}
    if not PD_CLI.exists():
        block("design_engine_missing", f"/product-design 스크립트를 찾을 수 없습니다({PD_CLI}). 같은 엔진의 Skill을 함께 설치하세요.")
    p = subprocess.run([sys.executable, "-I", str(PD_CLI), "status", "--project", str(project)],
                       capture_output=True, text=True, timeout=120)
    try:
        out = json.loads(p.stdout)
    except json.JSONDecodeError:
        block("design_status_failed", "product-design status 출력을 해석할 수 없습니다.", raw=(p.stdout + p.stderr)[-800:])
    out["exit_code"] = p.returncode
    return out


def _approved_record(design_raw: dict, stage: str) -> dict | None:
    s = (design_raw.get("stages") or {}).get(stage) or {}
    return s.get("approved") if s.get("status") == "approved" and isinstance(s.get("approved"), dict) else None


def design_info(project: Path) -> dict:
    """디자인 준비 수준(L0–L3)과 승인 기준. 판정은 product-design status의 cross_verify를 따릅니다."""
    ds = design_status(project)
    if ds.get("absent"):
        return {"level": "L0", "present": False, "reason": "design.json 없음(/product-design 미사용)", "stages": {}}
    if not ds.get("stages"):
        return {"level": "L0", "present": True, "reason": f"디자인 상태를 읽을 수 없습니다: {ds.get('message')}", "stages": {},
                "status_error": ds.get("error")}
    raw = json.loads((project / DESIGN_STATE_REL).read_text(encoding="utf-8"))
    stages = ds["stages"]
    probs = (ds.get("cross_verify") or {}).get("problems", [])
    bad = {p.get("stage") for p in probs}
    wf = (ds.get("workflow") or {}).get("workflow") or ("v2" if (raw.get("config") or {}).get("workflow") == "v2" else "v1")
    gate = bool(((raw.get("config") or {}).get("gates") or {}).get("design_direction"))

    def ok(stage):
        return stages.get(stage, {}).get("status") == "approved" and stage not in bad

    info = {"present": True, "workflow": wf, "design_direction_gate": gate, "problems": probs,
            "stages": {k: {"status": v.get("status"), "approved_revision": v.get("approved_revision")} for k, v in stages.items()},
            "validity": (ds.get("validity") or {}).get("status")}
    if (ds.get("validity") or {}).get("status") == "outdated":
        info.update(level="L1", reason="디자인이 기획 변경으로 outdated입니다(/product-design에서 rebase 필요)")
    elif not (ok("ux_planning") and ok("ux_spec")):
        info.update(level="L1", reason="UX Spec이 승인되지 않았거나 승인 이후 파일이 바뀌었습니다")
    elif gate and not ok("design_direction"):
        info.update(level="L1", reason="design_direction 게이트가 켜져 있는데 Design Direction이 승인되지 않았습니다")
    elif ok("preview"):
        info.update(level="L3", reason="프리뷰 승인됨")
    else:
        info.update(level="L2", reason="UX Spec(+Design Direction) 승인, 프리뷰 미승인")
    info["basis"] = {
        "ux_spec_revision": (_approved_record(raw, "ux_spec") or {}).get("revision"),
        "design_direction_revision": (_approved_record(raw, "design_direction") or {}).get("revision"),
        "preview_revision": (_approved_record(raw, "preview") or {}).get("revision"),
    }
    info["approved_digests"] = {st: digest(rec.get("hashes")) for st in ("ux_planning", "ux_spec", "design_direction", "preview")
                                if (rec := _approved_record(raw, st))}
    return info


