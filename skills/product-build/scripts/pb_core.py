def input_baseline(project: Path, gate: dict, dinfo: dict) -> dict:
    """계획의 입력 기준선: 기획 승인 revision·해시, 디자인 단계 승인 revision·해시 요약, 계획이 읽는 디자인 문서 해시."""
    files = {}
    for rel in DESIGN_INPUT_FILES:
        h = sha_file(project / rel)
        if h:
            files[rel] = h
    return {
        "planning": {"discovery_revision": gate.get("discovery_approved_revision"), "planning_revision": gate.get("planning_approved_revision"),
                     "hashes": gate.get("planning_hashes", {})},
        "design": {"level": dinfo["level"], "workflow": dinfo.get("workflow"), "basis": dinfo.get("basis", {}),
                   "approved_digests": dinfo.get("approved_digests", {})},
        "design_files": files,
    }


def baseline_changes(old: dict, new: dict) -> list[str]:
    """계획을 무효로 만드는 입력 변화. 프리뷰가 새로 승인되는 것(L2 → L3)은 무효화가 아닙니다.
    프리뷰 승인 기록이 바뀌는 것은 계획이 그 승인에 기대고 있을 때(L3)만 무효입니다."""
    ch = []
    op, np_ = old.get("planning", {}), new.get("planning", {})
    for k in ("discovery_revision", "planning_revision"):
        if op.get(k) != np_.get(k):
            ch.append(f"planning.{k}: {op.get(k)} → {np_.get(k)}")
    for f in sorted(set(op.get("hashes", {})) | set(np_.get("hashes", {}))):
        if op.get("hashes", {}).get(f) != np_.get("hashes", {}).get(f):
            ch.append(f"{f}: 승인 해시 변경")
    od, nd = old.get("design", {}), new.get("design", {})
    for st in ("ux_planning", "ux_spec", "design_direction"):
        if od.get("approved_digests", {}).get(st) != nd.get("approved_digests", {}).get(st):
            ch.append(f"design.{st}: 승인 기록 변경")
    if od.get("level") == "L3" and od.get("approved_digests", {}).get("preview") != nd.get("approved_digests", {}).get("preview"):
        ch.append("design.preview: 계획 기준이었던 프리뷰 승인 기록 변경")
    rank = {"L0": 0, "L1": 1, "L2": 2, "L3": 3}
    if rank.get(nd.get("level"), 0) < rank.get(od.get("level"), 0):
        ch.append(f"design.level: {od.get('level')} → {nd.get('level')}")
    for f in sorted(set(old.get("design_files", {})) | set(new.get("design_files", {}))):
        if old.get("design_files", {}).get(f) != new.get("design_files", {}).get(f):
            ch.append(f"{f}: 내용 변경")
    return ch


# ---------------------------------------------------------------- 프로필
def _merge(base: dict, over: dict) -> dict:
    out = dict(base)
    for k, v in over.items():
        out[k] = _merge(base[k], v) if isinstance(v, dict) and isinstance(base.get(k), dict) else v
    return out


def load_profile(project: Path, required: bool = False) -> tuple[dict, list[str]]:
    p = project / PROFILE_REL
    if not p.exists():
        if required:
            block("no_profile", f"{PROFILE_REL}이 없습니다. init으로 만드세요.")
        return json.loads(json.dumps(DEFAULT_PROFILE)), []
    try:
        raw = tomllib.loads(p.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as e:
        return json.loads(json.dumps(DEFAULT_PROFILE)), [f"{PROFILE_REL}: TOML 문법 오류({e})"]
    prof = _merge(json.loads(json.dumps(DEFAULT_PROFILE)), raw)
    return prof, profile_problems(prof)


def profile_problems(prof: dict) -> list[str]:
    errs = []
    if prof["project"].get("order_strategy") not in ORDER_STRATEGIES:
        errs.append(f"project.order_strategy는 {'/'.join(ORDER_STRATEGIES)} 중 하나여야 합니다")
    for p in prof["scope"].get("priorities", []):
        if p not in ("Must", "Should", "Could"):
            errs.append(f"scope.priorities에 알 수 없는 값: {p}")
    ap = prof["approval"]
    if ap.get("default") not in ("auto", "user"):
        errs.append("approval.default는 auto 또는 user여야 합니다")
    if ap.get("waived_ui") not in ("auto", "user"):
        errs.append("approval.waived_ui는 auto 또는 user여야 합니다")
    for t in ap.get("user_required_tags", []):
        if t not in RISK_TAGS:
            errs.append(f"approval.user_required_tags에 알 수 없는 태그: {t}")
    for t in (ap.get("risk_keywords") or {}):
        if t not in RISK_TAGS:
            errs.append(f"approval.risk_keywords에 알 수 없는 태그: {t}")
    for k in ("must", "should", "risk"):
        if prof["evidence"].get(k) not in EVIDENCE_LEVELS:
            errs.append(f"evidence.{k}는 {'/'.join(EVIDENCE_LEVELS)} 중 하나여야 합니다")
    order = {"E0": 0, "E1": 1, "E2": 2, "EM": 3, "E3": 3}
    if order.get(prof["evidence"].get("risk"), 0) < order.get(prof["evidence"].get("must"), 0):
        errs.append("evidence.risk는 evidence.must보다 낮을 수 없습니다(보안·권한·데이터 손실은 강화 검증)")
    names = set()
    for i, s in enumerate(prof["verify"].get("steps", [])):
        if not isinstance(s, dict) or not s.get("name") or not s.get("run"):
            errs.append(f"verify.steps[{i}]: name과 run이 필요합니다")
            continue
        if s["name"] in names:
            errs.append(f"verify.steps: 이름 중복 {s['name']}")
        names.add(s["name"])
        if s.get("stage", "other") not in VERIFY_STAGES:
            errs.append(f"verify.steps[{s['name']}].stage는 {'/'.join(VERIFY_STAGES)} 중 하나여야 합니다")
        if "requires" in s and not isinstance(s["requires"], list):
            errs.append(f"verify.steps[{s['name']}].requires는 목록이어야 합니다")
    ex = prof.get("execution", {})
    if not isinstance(ex.get("max_retries"), int) or not 1 <= ex["max_retries"] <= 5:
        errs.append("execution.max_retries는 1–5 사이 정수여야 합니다(무한 재시도 금지)")
    if not isinstance(ex.get("lock_ttl_minutes"), (int, float)) or ex["lock_ttl_minutes"] < 5:
        errs.append("execution.lock_ttl_minutes는 5 이상이어야 합니다")
    if ex.get("dependency_min") not in ("implemented", "verified", "approved"):
        errs.append("execution.dependency_min은 implemented/verified/approved 중 하나여야 합니다")
    ts = prof["verify"].get("tag_style", "bracket")
    if any(x not in ("bracket", "prefix", "pytest_name") for x in (ts if isinstance(ts, list) else [ts])):
        errs.append("verify.tag_style은 bracket·prefix·pytest_name 중 하나 또는 그 목록이어야 합니다")
    for s in prof["verify"].get("steps", []):
        rep = s.get("report") if isinstance(s, dict) else None
        if rep is not None:
            if not isinstance(rep, dict) or rep.get("format") not in ("pb-json", "junit-xml") or bool(rep.get("file")) == bool(rep.get("path")):
                errs.append(f"verify.steps[{s.get('name')}].report는 format(pb-json|junit-xml)과 file(실행별 폴더 안) 또는 path(고정 경로) 중 하나가 필요합니다")
            elif rep.get("path") and (rep["path"].startswith("/") or ".." in rep["path"].split("/")):
                errs.append(f"verify.steps[{s.get('name')}].report.path는 저장소 안 상대 경로여야 합니다")
            elif rep.get("file") and ("/" in rep["file"] or ".." in rep["file"]):
                errs.append(f"verify.steps[{s.get('name')}].report.file은 파일 이름만 씁니다")
    for k in ("source", "tests", "components", "exclude"):
        if not isinstance(prof["paths"].get(k, []), list):
            errs.append(f"paths.{k}는 목록이어야 합니다")
    return errs


def git_lines(project: Path, *args: str) -> list[str]:
    p = subprocess.run(["git", "-C", str(project), *args], capture_output=True, text=True)
    return [line for line in p.stdout.splitlines() if line.strip()] if p.returncode == 0 else []
