def load_state(project: Path) -> dict | None:
    p = project / STATE_REL
    if not p.exists():
        return None
    try:
        st = json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        block("invalid_state", f"{STATE_REL}을 읽을 수 없습니다({e}). 자동으로 고치지 않습니다.")
    probs = state_problems(st)
    if probs:
        block("invalid_state", "상태 파일 구조가 올바르지 않습니다. 자동으로 고치지 않습니다.", problems=probs)
    return st


def state_problems(st) -> list[str]:
    if not isinstance(st, dict):
        return ["최상위가 객체가 아닙니다"]
    probs = []
    if st.get("schema_version") != SCHEMA_VERSION:
        probs.append(f"schema_version이 {SCHEMA_VERSION}이 아닙니다(현재: {st.get('schema_version')!r}) — 이 엔진 버전이 지원하지 않습니다")
    plan = st.get("plan")
    if not isinstance(plan, dict) or plan.get("status") not in PLAN_STATUSES or not isinstance(plan.get("revision"), int):
        probs.append("plan.status·revision이 올바르지 않습니다")
    else:
        if plan["status"] == "approved" and not isinstance(plan.get("approved"), dict):
            probs.append("approved 상태인데 approved 기록이 없습니다(수동 편집 의심)")
        if plan["status"] == "awaiting_approval" and not isinstance(plan.get("submitted"), dict):
            probs.append("awaiting_approval 상태인데 submitted 기록이 없습니다(수동 편집 의심)")
    for k in ("waivers", "history"):
        if not isinstance(st.get(k), list):
            probs.append(f"{k}가 목록이 아닙니다")
    if not isinstance(st.get("batches"), dict):
        probs.append("batches가 객체가 아닙니다")
    else:
        for bid, b in st["batches"].items():
            if not isinstance(b, dict) or b.get("status") not in BATCH_STATUSES:
                probs.append(f"batches.{bid}.status가 올바르지 않습니다")
                continue
            s = b["status"]
            if s in ("implemented", "verified", "verify_failed", "stale", "approved", "imported") and not ((b.get("run") or {}).get("submitted")):
                probs.append(f"batches.{bid}: {s}인데 구현 제출 기록(run.submitted)이 없습니다(수동 편집 의심)")
            if s in ("verified", "stale", "approved") and not (isinstance(b.get("verification"), dict) and b["verification"].get("digest") and b["verification"].get("run_id")):
                probs.append(f"batches.{bid}: {s}인데 검증 실행 기록(verification.run_id·digest)이 없습니다(수동 편집 의심)")
            if s == "approved" and not any(x.get("valid") for x in b.get("approvals", [])):
                probs.append(f"batches.{bid}: approved인데 유효한 사용자 승인 기록이 없습니다(수동 편집 의심)")
            for o in b.get("target_overrides", []):
                if not (o.get("statement") and o.get("reason")):
                    probs.append(f"batches.{bid}: 사용자 승인 문장 없는 목표 변경 기록이 있습니다(수동 편집 의심)")
    return probs


