# ---------------------------------------------------------------- 출력·오류
class Blocked(Exception):
    def __init__(self, error: str, message: str, **extra):
        super().__init__(message)
        self.payload = {"ok": False, "error": error, "message": message, **extra}


def emit(obj: dict, code: int = 0) -> None:
    sys.stdout.write(json.dumps(obj, ensure_ascii=False, indent=2) + "\n")
    sys.exit(code)


def block(error: str, message: str, **extra) -> None:
    raise Blocked(error, message, **extra)


def now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha_file(p: Path) -> str | None:
    return sha256_bytes(p.read_bytes()) if p.is_file() else None


def digest(obj) -> str:
    return sha256_bytes(json.dumps(obj, ensure_ascii=False, sort_keys=True).encode("utf-8"))


# ---------------------------------------------------------------- 소유 경로 쓰기
def is_owned(rel: str) -> bool:
    rel = rel.replace("\\", "/")
    if rel.startswith("/") or ".." in Path(rel).parts:
        return False
    return rel == STATE_REL or any(rel.startswith(p) for p in OWNED if p.endswith("/"))


def is_protected(rel: str) -> bool:
    rel = rel.replace("\\", "/")
    while rel.startswith("./"):
        rel = rel[2:]
    return any(rel == p or (p.endswith("/") and rel.startswith(p)) for p in PROTECTED)


def write_owned(project: Path, rel: str, text: str) -> None:
    """이 Skill 소유 경로만 원자적으로 씁니다. 그 밖의 경로는 거부합니다(보호 경로 보장)."""
    if not is_owned(rel) or is_protected(rel):
        raise RuntimeError(f"product-build는 {rel}을 쓸 수 없습니다(소유 경로 밖)")
    p = project / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_name(p.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, p)


